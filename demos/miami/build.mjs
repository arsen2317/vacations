import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import react from '@vitejs/plugin-react'
import { build } from 'vite'

const result = await build({
  root: fileURLToPath(new URL('.', import.meta.url)),
  configFile: false,
  publicDir: false,
  plugins: [react()],
  build: {
    write: false,
    modulePreload: false,
  },
})

const html = result.output.find(file => file.fileName === 'index.html')
const script = result.output.find(file => file.type === 'chunk' && file.isEntry)

if (!html || !script || result.output.length !== 2) {
  throw new Error('Expected the demo to build to one HTML file and one JavaScript entry.')
}

const htmlWithScript = html.source.replace(
  /<script type="module"[^>]* src="[^"]+"><\/script>/,
  () => `<script type="module">${script.code.replace(/<\/script/gi, '<\\/script')}</script>`,
)
if (htmlWithScript === html.source) throw new Error('Could not inline the demo script.')

await writeFile(
  new URL('./vacation-miami.html', import.meta.url),
  '<!-- Generated by node demos/miami/build.mjs -->\n' + htmlWithScript,
)
